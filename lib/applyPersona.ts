// ─────────────────────────────────────────────────────────────
// applyPersona — SOAP テキストへのペルソナ変換（軸ベース設計）
//
// 【設計方針】
//   - 変換軸（AxisWeights）で人格を表現する。人格ごとの if 分岐なし。
//   - 人格を追加する場合は PERSONA_PROFILES にエントリを追加するだけ。
//     既存のルールセット・型定義・applyPersona 関数は変更不要。
//
// 【変換軸】
//   formality  : 0.0（常体）→ 1.0（丁寧体）  ── 文末を敬体に変換
//   softness   : 0.0（直接）→ 1.0（柔らか）  ── 指示表現を和らげる
//   density    : 0.0（詳細）→ 1.0（簡潔）    ── 敬体→体言止め・冗長表現を圧縮
//   directness : 0.0（やわ）→ 1.0（直接）    ── 現時点では将来拡張用
//
// 【適用ルール】
//   formality >= THRESHOLD.formality → 丁寧体ルールを適用
//   softness  >= THRESHOLD.softness  → 柔らかい表現ルールを追加適用
//   density   >= THRESHOLD.density   → 簡潔圧縮ルールを適用（formality と排他）
//
// 【density の位置づけ】
//   density >= 閾値の場合、formality ルールは適用しない（両立しない）。
//   density は文末を体言止め・短縮形に変換し、冗長な助動詞を除去する。
//   医療的意味の変更・文の削除は行わない。
//
// 【除外ライン】
//   isMedicalRecord() に該当する行はペルソナ変換対象外:
//     - 「次回〜確認。」系（記録・申し送り定型文）
//     - 「〜ことを説明。」系（指導記録）
//     - 「〜について指導。」「〜よう助言。」系
// ─────────────────────────────────────────────────────────────

// ─────────────────────────────────────────────────────────────
// 変換軸の型定義
// ─────────────────────────────────────────────────────────────

export interface AxisWeights {
  /** 丁寧度: 0.0（常体）→ 1.0（丁寧体）*/
  formality: number
  /** 柔らかさ: 0.0（直接）→ 1.0（柔らか）*/
  softness: number
  /** 情報密度: 0.0（詳細）→ 1.0（簡潔）— 体言止め・冗長語除去 */
  density: number
  /** 命令強度: 0.0（やわらかい）→ 1.0（直接）— 将来拡張用 */
  directness: number
}

// ─────────────────────────────────────────────────────────────
// ペルソナ種別
// ─────────────────────────────────────────────────────────────

/** ペルソナ種別 */
export type PersonaId = 'polite' | 'concise' | 'gentle'

/** ペルソナ表示ラベル */
export const PERSONA_LABELS: Record<PersonaId, string> = {
  polite:  '丁寧',
  concise: '簡潔',
  gentle:  'やさしい',
}

// ─────────────────────────────────────────────────────────────
// ペルソナ定義（軸の重みマップ）
//
// 人格を追加する場合: ここにエントリを追加し、PersonaId に型を追加するだけ。
// applyPersona / AxisWeights / ルールセットは変更不要。
// ─────────────────────────────────────────────────────────────

const PERSONA_PROFILES: Record<PersonaId, AxisWeights> = {
  /** 丁寧（baseline）: 常体を敬体に変換。柔らかさなし。 */
  polite: {
    formality:  1.0,
    softness:   0.0,
    density:    0.0,
    directness: 0.5,
  },
  /** 簡潔: 体言止め・冗長語除去。敬体変換なし・柔らかさなし。 */
  concise: {
    formality:  0.0,
    softness:   0.0,
    density:    1.0,
    directness: 1.0,
  },
  /** やさしい: 丁寧ベース + 柔らかい表現。 */
  gentle: {
    formality:  1.0,
    softness:   1.0,
    density:    0.0,
    directness: 0.0,
  },
}

// ─────────────────────────────────────────────────────────────
// 軸適用閾値
// ─────────────────────────────────────────────────────────────

const THRESHOLD = {
  formality: 0.5,
  softness:  0.5,
  density:   0.5,
} as const

// ─────────────────────────────────────────────────────────────
// 申し送り・closing 定型文の識別
//
// 以下の行はペルソナ変換対象外:
//   - 「次回、〜確認。」系（記録・申し送り定型文）
//   - 「〜ことを説明。」「〜必要があることを説明。」系（指導記録）
//
// 行単位で判定する（1行がまるごと定型文の場合のみ除外）。
// ─────────────────────────────────────────────────────────────

function isMedicalRecord(line: string): boolean {
  const t = line.trim()
  // 次回〜確認。 / 次回も〜確認。
  if (/^次回[、,，]/.test(t) && /確認[。.]$/.test(t)) return true
  // 〜ことを説明。 / 〜必要があることを説明。 / 〜するよう説明。
  if (/(?:ことを|ことについて|よう)説明[。.]$/.test(t)) return true
  // 〜について指導。 / 〜よう指導。 / 〜よう助言。
  if (/(?:について|よう)(?:指導|助言)[。.]$/.test(t)) return true
  return false
}

// ─────────────────────────────────────────────────────────────
// 行単位で変換を適用するユーティリティ
// ─────────────────────────────────────────────────────────────

function transformLines(text: string, transform: (line: string) => string): string {
  return text
    .split('\n')
    .map(line => isMedicalRecord(line) ? line : transform(line))
    .join('\n')
}

// ─────────────────────────────────────────────────────────────
// 軸別ルールセット
//
// 各ルールセットは独立した文字列変換の配列。
// 適用順序: formality → softness（softness は formality 後の文字列に適用）
// ─────────────────────────────────────────────────────────────

type ReplacePair = [RegExp | string, string]

/** formality ルール: 常体 → 丁寧体 */
const FORMALITY_RULES: ReplacePair[] = [
  // 〜した → 〜しました（「〜ました。」は除外: 直前が「ま」= 既に敬体）
  [/(?<!ま)した。/g, 'しました。'],
  // 〜である → 〜です
  [/である。/g, 'です。'],
  // 〜と考える → 〜と考えます
  [/と考える。/g, 'と考えます。'],
  // 〜認める → 〜認めます
  [/を認める。/g, 'を認めます。'],
  [/は認める。/g, 'は認めます。'],
  // 〜認めない → 〜認めません
  [/を認めない。/g, 'を認めません。'],
  [/は認めない。/g, 'は認めません。'],
  // 〜必要 → 〜必要です
  [/が必要。/g, 'が必要です。'],
  [/は必要。/g, 'は必要です。'],
  // 〜継続する → 〜継続します
  [/継続する。/g, '継続します。'],
  // 〜確認する → 〜確認いたします
  [/確認する。/g, '確認いたします。'],
  // 〜注意する → 〜注意します
  [/注意する。/g, '注意します。'],
  // 〜できない → 〜できません
  [/できない。/g, 'できません。'],
  // 〜可能性がある → 〜可能性があります
  [/可能性がある。/g, '可能性があります。'],
  // 〜ことがある / 〜場合がある → 〜ことがあります / 〜場合があります
  [/ことがある。/g, 'ことがあります。'],
  [/場合がある。/g, '場合があります。'],
  // 〜となる → 〜となります
  [/となる。/g, 'となります。'],
  // 〜重要 → 〜重要です
  [/が重要。/g, 'が重要です。'],
]

/**
 * density ルール: 文末の冗長語・評価定型句を圧縮する
 *
 * 【原則】
 *   - 「文末圧縮」と「定型評価語の圧縮」に限定する
 *   - 主語・薬剤名・症状名・評価対象は絶対に消さない
 *   - 文の前半（主部・述部の核）を変化させるパターンは禁止
 *   - 医療的意味の変更・文の削除は禁止
 *   - closing / follow-up 行の変換は禁止（isMedicalRecord() で除外済み）
 *
 * 【許可パターン】
 *   ① 評価語 + 「があります/がある」→「あり」（可能性あり、必要あり、ことあり、場合あり）
 *      文の中核は「可能性」「必要」「こと」「場合」が保持される。
 *   ② 文末の「〜です。」→「。」（体言止め）
 *      「血糖コントロール良好です。」→「血糖コントロール良好。」
 *      主語・内容はそのまま。
 *   ③ 動詞固定列挙：動詞+「します/しません/を認めます/を認めません」→ 動詞体言止め
 *      「継続します。」→「継続。」のように、動詞全体を体言止めにする形のみ許可。
 *      「を認めます。」→「を認める。」のように主語が落ちないパターンのみ許可。
 *
 * 【禁止パターン】（削除した理由）
 *   × となりました。→ となった。：「リベルサス継続投与となりました。」→「となった。」で主語欠損
 *   × になりました。→ になった。：同上
 *   × しました。→ した。（汎用）：「継続投与としました。」→「した。」で内容欠損
 *   × ます。→ る。（汎用）：任意の述語を置換しうる。意図しない変換のリスク大
 *   × 認めません。→ 認めず。：「は/を」が落ちるため前半欠損
 *   × できません。→ 不可。：意味が変わりすぎる（医療文書で「不可」は強すぎる）
 */
const DENSITY_RULES: ReplacePair[] = [
  // ── ① 評価語 + 「がある/があります」→「あり」─────────────────
  // 可能性あり（敬体・常体両対応）
  [/可能性があります。/g, '可能性あり。'],
  [/可能性がある。/g, '可能性あり。'],
  // 必要あり（敬体・常体両対応）
  [/必要があります。/g, '必要あり。'],
  [/必要がある。/g, '必要あり。'],
  // ことあり（敬体・常体両対応）
  [/ことがあります。/g, 'ことあり。'],
  [/ことがある。/g, 'ことあり。'],
  // 場合あり（敬体・常体両対応）
  [/場合があります。/g, '場合あり。'],
  [/場合がある。/g, '場合あり。'],
  // 訴えあり（敬体・常体両対応）
  [/の訴えがあります。/g, 'の訴えあり。'],
  [/の訴えがある。/g, 'の訴えあり。'],
  // 残存する汎用「があります。」→「あり。」（上記で捕捉されなかった評価語用）
  [/があります。/g, 'あり。'],

  // ── ② 文末「〜です。」→ 体言止め（「。」のみ残す）─────────────
  [/です。/g, '。'],

  // ── ③ 動詞固定列挙（主語・内容が欠損しないパターンのみ）────────
  // 「継続します。」→「継続。」
  [/継続します。/g, '継続。'],
  [/継続する。/g, '継続。'],
  // 「確認します/いたします。」→「確認。」
  [/確認します。/g, '確認。'],
  [/確認いたします。/g, '確認。'],
  [/確認する。/g, '確認。'],
  // 「注意します。」→「注意。」
  [/注意します。/g, '注意。'],
  [/注意する。/g, '注意。'],
  // 「を認めます。」→「を認める。」（主語保持: 「は/を」がついている前提）
  [/を認めます。/g, 'を認める。'],
  [/は認めます。/g, 'は認める。'],
  // 「を認めません。」→「を認めない。」（主語保持）
  [/を認めません。/g, 'を認めない。'],
  [/は認めません。/g, 'は認めない。'],
  // 「と考えます。」→「と考える。」（前半の主語・論拠は保持される）
  [/と考えます。/g, 'と考える。'],
  // 「となります。」→「となる。」（前半の主語が保持される形のみ）
  [/となります。/g, 'となる。'],
]

/** softness ルール: formality 適用後の文字列に追加適用 */
const SOFTNESS_RULES: ReplacePair[] = [
  // 〜ご相談ください → お気軽にご相談ください（先頭にお気軽にがない場合のみ）
  [/(?<!お気軽に)ご相談ください。/g, 'お気軽にご相談ください。'],
  // 〜確認いたします → 〜確認していきます（formality後の文字列に適用）
  [/確認いたします。/g, '確認していきます。'],
  // 〜注意します → 〜お気をつけください
  [/注意します。/g, 'お気をつけください。'],
  // 〜受診してください → 〜受診いただくことをおすすめします
  [/受診してください。/g, '受診いただくことをおすすめします。'],
]

// ─────────────────────────────────────────────────────────────
// ルールセットを1行に適用するユーティリティ
// ─────────────────────────────────────────────────────────────

function applyRules(line: string, rules: ReplacePair[]): string {
  let result = line
  for (const [pattern, replacement] of rules) {
    result = result.replace(pattern as RegExp, replacement)
  }
  return result
}

// ─────────────────────────────────────────────────────────────
// 軸ベース変換（コア）
//
// 人格ごとの if 分岐なし。
// AxisWeights の値と THRESHOLD で適用ルールセットを決定する。
//
// 適用順序:
//   1. density >= threshold → DENSITY_RULES のみ（formality は非適用）
//   2. density <  threshold かつ formality >= threshold → FORMALITY_RULES
//   3. softness >= threshold → SOFTNESS_RULES（density と排他: density適用時は非適用）
//
// density と formality は排他: density が高い場合（簡潔モード）は敬体化しない。
// ─────────────────────────────────────────────────────────────

function applyAxes(line: string, weights: AxisWeights): string {
  let result = line
  if (weights.density >= THRESHOLD.density) {
    // 簡潔モード: 体言止め・冗長語除去（formality・softness は非適用）
    result = applyRules(result, DENSITY_RULES)
  } else {
    // 丁寧/やさしいモード
    if (weights.formality >= THRESHOLD.formality) {
      result = applyRules(result, FORMALITY_RULES)
    }
    if (weights.softness >= THRESHOLD.softness) {
      result = applyRules(result, SOFTNESS_RULES)
    }
  }
  return result
}

// ─────────────────────────────────────────────────────────────
// 公開 API
// ─────────────────────────────────────────────────────────────

/**
 * 単一テキストにペルソナ変換を適用する。
 * - 行単位で変換。isMedicalRecord() に該当する行はスキップ。
 * - ON時は必ずどちらかのペルソナが適用される（OFF は呼び出し元で制御）。
 * - 人格ごとの if 分岐なし。PERSONA_PROFILES の軸重みを参照して変換。
 */
export function applyPersona(text: string, persona: PersonaId): string {
  if (!text) return text
  const weights = PERSONA_PROFILES[persona]
  return transformLines(text, line => applyAxes(line, weights))
}

/**
 * SoapFields 全体にペルソナ変換を適用する。
 *
 * - enabled=false の場合は fields をそのまま返す（参照同一）
 * - enabled=true の場合は必ずペルソナ変換済み新オブジェクトを返す
 */
export function applyPersonaToFields(
  fields: { S: string; O: string; A: string; P: string },
  enabled: boolean,
  persona: PersonaId,
): { S: string; O: string; A: string; P: string } {
  if (!enabled) return fields
  return {
    S: applyPersona(fields.S, persona),
    O: applyPersona(fields.O, persona),
    A: applyPersona(fields.A, persona),
    P: applyPersona(fields.P, persona),
  }
}
